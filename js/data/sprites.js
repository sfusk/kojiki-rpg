// 各スプライト定義をoffscreen canvasに1px=1pxで描画し、Mapで返す
// グリッドサイズは定義（rows）から動的に決定する（32x32を想定）
export function buildSprites() {
  const map = new Map();
  for (const [name, rows] of Object.entries(SPRITES)) {
    const height = rows.length;
    const width = rows[0].length;
    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    const ctx = canvas.getContext('2d');
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        if (ch === '.') continue;
        const color = PAL[ch];
        if (!color) continue;
        ctx.fillStyle = color;
        ctx.fillRect(x, y, 1, 1);
      }
    }
    map.set(name, canvas);
  }
  return map;
}

// タイル定義をoffscreen canvasに1px=1pxで描画し、Mapで返す
// buildSpritesとの違い：TILESは不透明タイルのため '.' も塗り色として扱う（透過しない）
export function buildTiles() {
  const map = new Map();
  for (const [name, rows] of Object.entries(TILES)) {
    const height = rows.length;
    const width = rows[0].length;
    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    const ctx = canvas.getContext('2d');
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        ctx.fillStyle = PAL[ch] || '#000';
        ctx.fillRect(x, y, 1, 1);
      }
    }
    map.set(name, canvas);
  }
  return map;
}
