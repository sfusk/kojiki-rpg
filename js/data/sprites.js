// 各スプライト定義をoffscreen canvasに1px=1pxで描画し、Mapで返す
export function buildSprites() {
  const map = new Map();
  for (const [name, rows] of Object.entries(SPRITES)) {
    const canvas = document.createElement('canvas');
    canvas.width = 16;
    canvas.height = 16;
    const ctx = canvas.getContext('2d');
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        if (ch === '.') continue;
        const color = PAL[ch];
        if (!color) continue;
        ctx.fillStyle = color;
        ctx.fillRect(x, y, 1, 1);
      }
    }
    map.set(name, canvas);
  }
  return map;
}
