// 難読語の読み（ルビ）辞書。クイズの選択肢に小さく振り仮名を添えるために使う。
// 見出しは表示されている語と完全一致させること。読みが自明な語（カタカナ表記の
// 神名や「櫛」「舟」など）は載せない。載っていない語にはルビが出ないだけで害はない。
export const READINGS = {
  // 神器・武具
  草薙剣: 'くさなぎのつるぎ',
  天沼矛: 'あめのぬぼこ',
  十拳剣: 'とつかのつるぎ',
  八咫鏡: 'やたのかがみ',
  勾玉: 'まがたま',
  矛: 'ほこ',
  // 神・人・生き物
  八咫烏: 'やたがらす',
  雉: 'きじ',
  鳶: 'とび',
  筍: 'たけのこ',
  櫛: 'くし',
  // 地名
  淡路島: 'あわじしま',
  佐渡島: 'さどのしま',
  隠岐島: 'おきのしま',
  筑紫島: 'つくしのしま',
};

// 語に対応する読みを返す（未登録ならnull）
export function readingOf(word) {
  return Object.prototype.hasOwnProperty.call(READINGS, word) ? READINGS[word] : null;
}
